"""
AI or Real? — a Streamlit website that detects whether an image is
AI-generated or a real photo.

Totally Python: this file is the whole website (no separate frontend).
The styling below is small CSS injected from Python, which is the
standard way to theme a Streamlit app.

Run it:
    pip install -r requirements.txt
    streamlit run app.py
"""

import streamlit as st
from PIL import Image

from detector import MODEL_ID, classify, load_detector

st.set_page_config(
    page_title="AI or Real? · Image Detector",
    page_icon="🔍",
    layout="centered",
    menu_items={"About": "AI or Real? — check whether an image is AI-generated or a real photo."},
)

# ---------------------------------------------------------------- styling
st.markdown(
    """
    <style>
      .block-container { padding-top: 1.6rem; max-width: 880px; }
      #MainMenu, footer { visibility: hidden; }

      .hero {
        background: linear-gradient(120deg, #26282c 0%, #141518 55%, #000000 100%);
        color: white; border-radius: 20px;
        border: 1px solid #33373d;
        padding: 2.1rem 2rem 1.7rem 2rem; margin-bottom: 1.4rem;
      }
      .hero h1 { color: white; font-size: 2.5rem; margin: 0 0 0.4rem 0; padding: 0; }
      .hero p  { color: rgba(255,255,255,0.92); font-size: 1.06rem; margin: 0; }
      .hero .pill {
        display: inline-block; background: rgba(255,255,255,0.18);
        border: 1px solid rgba(255,255,255,0.35); color: white;
        border-radius: 999px; padding: 0.18rem 0.75rem;
        font-size: 0.8rem; margin-top: 0.9rem;
      }

      .verdict {
        border-radius: 16px; padding: 1.3rem 1.4rem; margin-bottom: 1rem;
        border: 1px solid transparent;
      }
      .verdict-real { background: #171a1f; border-color: #e5e7eb; }
      .verdict-ai   { background: #171a1f; border-color: #9ca3af; border-style: dashed; }

      .note {
        background: #171a1f; border: 1px solid #33373d;
        border-left: 4px solid #e5e7eb; border-radius: 10px;
        padding: 0.85rem 1rem; margin: 0.6rem 0;
      }
      .verdict .label { font-size: 0.85rem; text-transform: uppercase;
                        letter-spacing: 0.06em; opacity: 0.7; margin: 0; }
      .verdict .big   { font-size: 1.9rem; font-weight: 700; margin: 0.15rem 0; }
      .verdict .sub   { margin: 0; opacity: 0.85; }

      div.stButton > button, div.stFileUploader button {
        border-radius: 999px; font-weight: 600;
      }
      button[data-testid="stBaseButton-primary"],
      div.stButton > button[kind="primary"] {
        background-color: #ffffff !important; color: #0b0d10 !important;
        border-color: #ffffff !important;
      }
      div[data-testid="stFileUploader"] section {
        border-radius: 16px; border: 1.5px dashed #6b7280; background: #171a1f;
        padding: 1.2rem;
      }
    </style>
    """,
    unsafe_allow_html=True,
)


@st.cache_resource(show_spinner="Loading the detection model — the first run downloads it (~350 MB)...")
def get_detector():
    return load_detector()


if "history" not in st.session_state:
    st.session_state.history = []
if "result" not in st.session_state:
    st.session_state.result = None
if "uploader_key" not in st.session_state:
    st.session_state.uploader_key = 0

# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("ℹ️ About")
    st.write(
        "Upload a photo and a pretrained vision model estimates whether "
        "it was **generated by AI** or **captured by a camera**."
    )
    st.caption(f"Model: `{MODEL_ID}`")
    st.divider()
    st.subheader("💡 Tips for a fair test")
    st.write(
        "- Use the **original** image file when you can\n"
        "- Screenshots and re-saves weaken the signal\n"
        "- Close-ups and plain backgrounds are hardest to judge"
    )
    st.divider()
    st.caption(
        "Your image is analysed by the model and is **not stored**. "
        "Results are a signal, not proof."
    )

# ---------------------------------------------------------------- hero
st.markdown(
    """
    <div class="hero">
      <h1>🔍 AI or Real?</h1>
      <p>Drop in any image and find out in seconds whether it looks
         AI-generated or like a real photo — with a confidence score.</p>
      <span class="pill">100% Python · Powered by a Vision Transformer model</span>
    </div>
    """,
    unsafe_allow_html=True,
)

# ---------------------------------------------------------------- how it works
step1, step2, step3 = st.columns(3)
with step1:
    with st.container(border=True):
        st.markdown("**1 · 📤 Upload**")
        st.caption("JPG, PNG or WEBP, up to 200 MB")
with step2:
    with st.container(border=True):
        st.markdown("**2 · 🧠 AI analysis**")
        st.caption("A vision model scans the image")
with step3:
    with st.container(border=True):
        st.markdown("**3 · ✅ Verdict**")
        st.caption("AI-generated or Real, with confidence")

st.write("")

# ---------------------------------------------------------------- upload + action
uploaded = st.file_uploader(
    "Upload an image to check",
    type=["jpg", "jpeg", "png", "webp"],
    key=f"uploader_{st.session_state.uploader_key}",
    help="Your image is analysed by the model and is not stored.",
)

if uploaded is None:
    st.markdown(
        '<div class="note">👆 Upload an image above to get started — a family photo, a screenshot, anything.</div>',
        unsafe_allow_html=True,
    )
    st.session_state.result = None
else:
    image = Image.open(uploaded)
    left, right = st.columns([3, 2], gap="large")

    with left:
        st.image(image, caption=uploaded.name, use_container_width=True)

    with right:
        size_kb = max(1, round(len(uploaded.getvalue()) / 1024))
        st.markdown("**Image details**")
        st.write(f"📄 File: `{uploaded.name}`")
        st.write(f"🖼️ Size: {image.width} × {image.height} px")
        st.write(f"💾 File size: {size_kb} KB")

        check = st.button("🔎 Check this image", type="primary", use_container_width=True)
        clear = st.button("Clear", use_container_width=True)

        if clear:
            st.session_state.result = None
            st.session_state.uploader_key += 1
            st.rerun()

        if check:
            try:
                detector = get_detector()
            except Exception as exc:  # model download / load failure
                st.error(f"Couldn't load the detection model. Details: {exc}")
                st.stop()

            with st.spinner("Analysing the image..."):
                result = classify(detector, image)

            st.session_state.result = result
            st.session_state.history.insert(
                0,
                {
                    "name": uploaded.name,
                    "verdict": result["verdict"],
                    "confidence": result["confidence"],
                },
            )

    # ------------------------------------------------------------ result
    result = st.session_state.result
    if result is not None:
        st.write("")
        verdict = result["verdict"]
        confidence = result["confidence"]
        scores = result["scores"]
        is_ai = verdict == "AI-generated"

        css_class = "verdict-ai" if is_ai else "verdict-real"
        emoji = "🤖" if is_ai else "📷"
        headline = "AI-generated" if is_ai else "Real photo"
        sub = (
            "This image shows patterns typical of AI-generated images."
            if is_ai
            else "This image looks like a genuine camera photo."
        )
        st.markdown(
            f"""
            <div class="verdict {css_class}">
              <p class="label">Verdict</p>
              <p class="big">{emoji} {headline}</p>
              <p class="sub">{sub} The model is <b>{confidence:.0%} confident</b>.</p>
            </div>
            """,
            unsafe_allow_html=True,
        )

        bar_left, bar_right = st.columns(2)
        with bar_left:
            st.metric("🤖 AI-generated", f"{scores['AI-generated']:.0%}")
            st.progress(scores["AI-generated"])
        with bar_right:
            st.metric("📷 Real", f"{scores['Real']:.0%}")
            st.progress(scores["Real"])

        if confidence >= 0.85:
            signal_note = "● <b>Strong signal</b> — the model is quite sure about this one."
        elif confidence >= 0.65:
            signal_note = "● <b>Moderate signal</b> — fairly likely, but not certain."
        else:
            signal_note = (
                "● <b>Weak signal</b> — this one is close to the line. "
                "Treat it as <b>uncertain</b>, not proof either way."
            )
        st.markdown(f'<div class="note">{signal_note}</div>', unsafe_allow_html=True)

# ---------------------------------------------------------------- history + help
if st.session_state.history:
    with st.expander(f"🕘 Your recent checks ({len(st.session_state.history)})"):
        for item in st.session_state.history:
            icon = "🤖" if item["verdict"] == "AI-generated" else "📷"
            st.write(f"{icon} **{item['name']}** — {item['verdict']} ({item['confidence']:.0%} confident)")

with st.expander("❓ How do I read the result?"):
    st.write(
        "- **85%+ confidence** — strong signal, the model is quite sure\n"
        "- **65–85%** — moderate signal, fairly likely but not certain\n"
        "- **Below 65%** — weak signal, treat the result as uncertain\n\n"
        "No detector is perfect. Edited, cropped, or heavily compressed "
        "images can fool any model, so use this as one signal among others."
    )

st.divider()
st.caption("Built entirely in Python with Streamlit · Model: `dima806/deepfake_vs_real_image_detection`")
